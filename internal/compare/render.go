package compare

import (
	"fmt"
	"strings"
)

const nl = "\n"

const tick = "`"

// Markdown renders the report.
func Markdown(r *Report) string {
	var b strings.Builder
	labels := make([]string, 0, len(r.Inputs))
	for _, in := range r.Inputs {
		labels = append(labels, in.Label)
	}
	b.WriteString(`# ` + r.Title + nl + nl)
	b.WriteString(`Generated by cmd/compare. Volatile leaves (timestamps, durations, args) are excluded from the diff.` + nl + nl)

	b.WriteString(`## Inputs` + nl + nl)
	b.WriteString(`| Label | File |` + nl + `| --- | --- |` + nl)
	for _, in := range r.Inputs {
		b.WriteString(`| ` + esc(in.Label) + ` | ` + code(in.Path) + ` |` + nl)
	}
	for _, in := range r.Missing {
		b.WriteString(`| ` + esc(in.Label) + ` | ` + code(in.Path) + ` (missing, skipped) |` + nl)
	}
	b.WriteString(nl)

	writeTable(&b, `## Environment`, `Field`, labels, r.Meta, false)
	writeTable(&b, `## Status matrix`, `Probe`, labels, r.StatusRows, true)
	writeTable(&b, `## Differing values`, `Path`, labels, r.ValueRows, false)
	writeTable(&b, `## Summary counts`, `Counter`, labels, r.Summary, false)

	b.WriteString(`## Totals` + nl + nl)
	b.WriteString(fmt.Sprintf(`- Probes compared: %d`+nl, len(r.StatusRows)))
	b.WriteString(fmt.Sprintf(`- Probes whose status differs: %d`+nl, CountDiffers(r.StatusRows)))
	b.WriteString(fmt.Sprintf(`- Non-status values that differ: %d`+nl, len(r.ValueRows)))
	return b.String()
}

func writeTable(b *strings.Builder, heading, first string, labels []string, rows []Row, boldDiffers bool) {
	b.WriteString(heading + nl + nl)
	if len(rows) == 0 {
		b.WriteString(`(none)` + nl + nl)
		return
	}
	b.WriteString(`| ` + first)
	for _, l := range labels {
		b.WriteString(` | ` + esc(l))
	}
	b.WriteString(` | Differs |` + nl + `| ---`)
	for range labels {
		b.WriteString(` | ---`)
	}
	b.WriteString(` | --- |` + nl)
	for _, row := range rows {
		b.WriteString(`| ` + code(row.Path))
		for _, v := range row.Values {
			b.WriteString(` | ` + code(v))
		}
		mark := ``
		if row.Differs {
			mark = `yes`
			if boldDiffers {
				mark = `**yes**`
			}
		}
		b.WriteString(` | ` + mark + ` |` + nl)
	}
	b.WriteString(nl)
}

func esc(s string) string {
	return strings.ReplaceAll(s, `|`, `\|`)
}

func code(s string) string {
	if s == `` {
		return ``
	}
	return tick + esc(s) + tick
}
